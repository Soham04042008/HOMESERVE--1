/*
# Create bookings table

1. New Tables
- `bookings`
  - `id` (uuid, primary key)
  - `user_id` (uuid, not null, defaults to the authenticated user, references auth.users)
  - `booking_reference` (text, unique, human-readable reference e.g. HS-1001)
  - `service_name` (text, not null, e.g. "Plumbing Inspection")
  - `category` (text, not null, one of: Electrician, Plumbing, Cleaning, Carpentry, AC Repair, Painting, Other)
  - `professional_name` (text, not null)
  - `professional_avatar` (text, nullable, URL)
  - `professional_phone` (text, nullable)
  - `appointment_at` (timestamptz, not null, scheduled appointment date/time)
  - `location_area` (text, not null, e.g. "Panvel")
  - `location_address` (text, not null, full service address)
  - `price` (integer, not null, total in INR)
  - `payment_status` (text, not null, default 'Pending': Pending, Paid, Refunded)
  - `payment_method` (text, nullable, e.g. "Cash", "UPI", "Card")
  - `booking_status` (text, not null, default 'Confirmed': Pending, Confirmed, In Progress, Completed, Cancelled)
  - `customer_note` (text, nullable)
  - `cancellation_reason` (text, nullable)
  - `rating` (integer, nullable, 1-5, set after completion)
  - `review_text` (text, nullable)
  - `created_at` (timestamptz, default now())
2. Security
- Enable RLS on `bookings`.
- Owner-scoped CRUD: each authenticated user can only access rows they own.
  - SELECT: auth.uid() = user_id
  - INSERT: WITH CHECK auth.uid() = user_id
  - UPDATE: USING + WITH CHECK auth.uid() = user_id
  - DELETE: USING auth.uid() = user_id
3. Notes
- `user_id` defaults to auth.uid() so frontend inserts omitting user_id succeed.
- Payment status, final pricing, and admin-level status changes are protected at the
  application layer (the UPDATE policy allows owners to update their own rows, but the
  frontend never exposes payment_status/price controls to the customer; these are
  treated as read-only in the UI).
- Booking reference is unique; generated by the application as HS-<number>.
*/

CREATE TABLE IF NOT EXISTS bookings (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL DEFAULT auth.uid() REFERENCES auth.users(id) ON DELETE CASCADE,
  booking_reference text UNIQUE NOT NULL,
  service_name text NOT NULL,
  category text NOT NULL CHECK (category IN ('Electrician','Plumbing','Cleaning','Carpentry','AC Repair','Painting','Other')),
  professional_name text NOT NULL,
  professional_avatar text,
  professional_phone text,
  appointment_at timestamptz NOT NULL,
  location_area text NOT NULL,
  location_address text NOT NULL,
  price integer NOT NULL,
  payment_status text NOT NULL DEFAULT 'Pending' CHECK (payment_status IN ('Pending','Paid','Refunded')),
  payment_method text,
  booking_status text NOT NULL DEFAULT 'Confirmed' CHECK (booking_status IN ('Pending','Confirmed','In Progress','Completed','Cancelled')),
  customer_note text,
  cancellation_reason text,
  rating integer CHECK (rating >= 1 AND rating <= 5),
  review_text text,
  created_at timestamptz DEFAULT now()
);

ALTER TABLE bookings ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "select_own_bookings" ON bookings;
CREATE POLICY "select_own_bookings"
  ON bookings FOR SELECT
  TO authenticated
  USING (auth.uid() = user_id);

DROP POLICY IF EXISTS "insert_own_bookings" ON bookings;
CREATE POLICY "insert_own_bookings"
  ON bookings FOR INSERT
  TO authenticated
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "update_own_bookings" ON bookings;
CREATE POLICY "update_own_bookings"
  ON bookings FOR UPDATE
  TO authenticated
  USING (auth.uid() = user_id)
  WITH CHECK (auth.uid() = user_id);

DROP POLICY IF EXISTS "delete_own_bookings" ON bookings;
CREATE POLICY "delete_own_bookings"
  ON bookings FOR DELETE
  TO authenticated
  USING (auth.uid() = user_id);

CREATE INDEX IF NOT EXISTS idx_bookings_user_id ON bookings(user_id);
CREATE INDEX IF NOT EXISTS idx_bookings_status ON bookings(booking_status);
CREATE INDEX IF NOT EXISTS idx_bookings_appointment_at ON bookings(appointment_at);
